// Per-rank background art = the rank's sky (the Blender world background, no island).
export const RANK_BACKGROUNDS = {
  Grounded: require("../../assets/rank-grounded-sky.jpg"),
  Awakened: require("../../assets/rank-awakened.png"),
  Elevated: require("../../assets/rank-elevated.png"),
};

// Per-rank 360° turntable frame sets. Only Grounded has a rendered island so far.
export const RANK_ISLAND_FRAMES = {
  Grounded: ISLAND_360_FRAMES,
};

export function getIslandFrames(rankName) {
  return RANK_ISLAND_FRAMES[rankName] || null;
}

export function getRankBackground(rankName) {
  return RANK_BACKGROUNDS[rankName] || RANK_BACKGROUNDS.Grounded;
}
